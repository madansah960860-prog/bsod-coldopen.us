        <h2 class="section-head__title" id="editor-title">From the editor</h2>
        <p>We publish roughly six reviews a month. That is a deliberately small number. It means every game in the library was finished by the person whose name is on the review, and that the score was argued about by at least two other people before it went up.</p>
        <p>It also means we are late, often. Cadence Machine came out in June and we are writing about it in September, because the thing worth saying about it only became obvious somewhere around hour nine. We would rather be late and right.</p>
